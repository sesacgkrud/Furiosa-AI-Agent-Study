# [경사 하강법 (gradient descent)]
#   f(x) = x² - 4x + 6 의 최솟값 (x = 2, f = 2) 을 미분값(기울기) 으로 직접 찾아간다
#   - 기울기 f'(x) = 2x - 4 : x < 2 면 음수, x > 2 면 양수, x = 2 에서 0
#   - 갱신식 : x = x - learning_rate * f'(x)
#       기울기가 음수면 x 가 커지고, 양수면 x 가 작아져서 → 항상 최솟값 쪽으로 이동한다
#       최솟값에 가까울수록 기울기가 작아져 이동 폭도 줄어든다
#   - 신경망 훈련에서 x 는 가중치, f(x) 는 loss, learning_rate 는 한 번에 움직이는 비율이다
#
# [흐름]
#   1. 초깃값 x = -10.0 (f = 146) 에서 시작 (위 linspace x 는 gradient1 에서 가져온 것으로, 여기서 덮어쓴다)
#   2. 50 epoch 동안 x 를 갱신하며 epoch · x · f(x) 를 출력
#      "{:02d}" : 두 자리 정수 (00, 01 ...) / "{:6.5f}" : 소수 5 자리 실수
#   3. 결과 : x 는 -10 → 1.99983, f(x) 는 146 → 2.00000 으로 최솟값 (2, 2) 에 수렴

import numpy as np
import matplotlib.pyplot as plt

x = np.linspace(-1, 6, 100)
print(x, len(x))

f = lambda x : x**2 - 4*x + 6
gradient = lambda x : 2*x - 4       # f(x) 를 미분한 기울기 f'(x)

x = -10.0 # 초깃값
epochs = 50
learning_rate = 0.1

print("epoch \t x \t f(x)")
print("{:02d}\t {:6.5f}\t {:6.5f}\t".format(0, x, f(x)))

for i in range(epochs):
    x = x - learning_rate * gradient(x)     # 기울기 반대 방향으로 learning_rate 만큼 이동

    print("{:02d}\t {:6.5f}\t {:6.5f}\t".format(i+1, x, f(x)))

