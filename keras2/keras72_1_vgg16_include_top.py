# VGG16 : 미리 훈련된(pre-trained) 이미지 분류 모델을 불러와서 구조를 확인한다
#
# VGG16 이란
#  - 2014년 옥스퍼드 대학 VGG(Visual Geometry Group) 팀이 만든 CNN 모델
#  - 가중치가 있는 층이 16개 (Conv2D 13개 + Dense 3개) 라서 VGG16
#  - 모든 Conv2D 가 kernel_size=(3,3), padding='same', activation='relu'
#    → Conv2D 는 가로 세로를 그대로 두고 필터(채널) 수만 64 → 128 → 256 → 512 로 늘린다
#  - 블록(block1 ~ block5) 마다 끝에 MaxPooling2D 가 있어 가로 세로가 절반씩 줄어든다
#  - imagenet (사진 약 120만 장, 1000종) 으로 이미 훈련이 끝난 가중치를 그대로 내려받아 쓸 수 있다
#
# 지금까지와의 차이
#  - 지금까지는 Conv2D, Dense 를 직접 쌓고 가중치는 랜덤값에서 시작해서 훈련했다
#  - VGG16 은 층 구성과 훈련된 가중치를 한 줄로 불러온다 → 이 가중치를 내 데이터에 다시 쓰는 것이 전이학습
#    (실제로 cifar10 · cifar100 에 붙여 훈련한 것은 keras73_vgg16_01_cifar10.py / keras73_vgg16_02_cifar100.py)

