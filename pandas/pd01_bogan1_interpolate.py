"""
결측치 처리
1. 삭제 - 행 또는 열
2. 임의의 값
    - 0 : fillna
    - 평균 : mean (특히 이상치 조심)
    - 중위 : median
    - 앞값 : ffill
    - 뒷값 : bfill
    - 특정값 : 777 (조건 보고 넣는 게 낫다)
    - 최빈값
    - 기타 등등...
3. interpolate - 보간 (알려진 데이터 점 집합의 범위 내에 새 데이터 점을 추가하는 기법)
4. 모델 : .predict(값을 예측해서), (전혀 다른 모델 사용)
5. 부스팅(트리) 계열 모델 : 통상 결측치, 이상치에 대해 영향을 덜 받는다. (자유롭다)
6. 스케일링(RobustScaler 등...) - 이상치에 자유로움
"""

# [목적]
# 결측치(NaN) 처리 방법을 정리하고 (위 docstring), 그중 3. interpolate(보간) 를 날짜 인덱스 시계열에 적용해 본다.
#
# [흐름]
#   1. pd.to_datetime(문자열 리스트, dayfirst=True) : "일/월/년" 형식 문자열을 날짜로 바꾼다
#      → DatetimeIndex (dayfirst=True 가 없으면 "12/11/2026" 을 12월 11일로 읽는다)
#   2. 날짜를 인덱스로 하는 Series 를 만든다 (중간 3 칸이 NaN)
#   3. ts.interpolate() : 앞뒤 값을 직선(linear) 으로 이어 NaN 을 채운다
#      2 와 8 사이 NaN 2 칸 → 4, 6 / 10 과 14 사이 NaN 1 칸 → 12

import pandas as pd
import numpy as np
print(pd.__version__) # 3.1.0

dates = [
    "11/11/2026", "12/11/2026", "13/11/2026",
    "14/11/2026", "15/11/2026", "16/11/2026",
    "17/11/2026", "18/11/2026", "19/11/2026",
]

dates = pd.to_datetime(dates, dayfirst=True)
print(dates)

# DatetimeIndex(['2026-11-11', '2026-11-12', '2026-11-13', '2026-11-14',
#                '2026-11-15', '2026-11-16', '2026-11-17', '2026-11-18',
#                '2026-11-19'],
#               dtype='datetime64[us]', freq=None)

print("==============================")
ts = pd.Series([0, 2, np.nan, np.nan, 8, 10, np.nan, 14, 16 ], index=dates)
print(ts)

# 2026-11-11     0.0
# 2026-11-12     2.0
# 2026-11-13     NaN
# 2026-11-14     NaN
# 2026-11-15     8.0
# 2026-11-16    10.0
# 2026-11-17     NaN
# 2026-11-18    14.0
# 2026-11-19    16.0
# dtype: float64

print("==============================")
ts = ts.interpolate()
print(ts)

# 2026-11-11     0.0
# 2026-11-12     2.0
# 2026-11-13     4.0
# 2026-11-14     6.0
# 2026-11-15     8.0
# 2026-11-16    10.0
# 2026-11-17    12.0
# 2026-11-18    14.0
# 2026-11-19    16.0
# dtype: float64

# 중간값들은 linear로 채워진다.
# 마지막이 결측치일 경우, ffill (이전 값으로 채워진다.)
# 첫번째가 결측치일 경우, 처리 안 됨 (직접 처리해줘야 한다.)
